"""
Trajectory save/load utilities for agent execution traces.

- ``save_trajectory()`` — write a single agent run to a new JSON file.
- ``append_trajectory()`` — append to an existing JSON array (or create new).
- ``save_trajectories_batch()`` — write multiple results + summary to one file.

Each trajectory record includes ``prompt_tokens``, ``generated_tokens``,
and ``total_tokens`` breakdown.  Batch files end with a ``_summary`` entry
that aggregates token stats across all tasks.
"""

from __future__ import annotations

import json
import os
from datetime import datetime
from typing import Any, Dict, List, Optional

from agentic.agent import AgentResult


# ---------------------------------------------------------------------------
# AgentResult → trajectory record
# ---------------------------------------------------------------------------

def agent_result_to_record(
    agent_result: AgentResult,
    model_id: str = "",
    config_name: str = "",
    task_id: str = "",
    prompt_tokens: int = 0,
    generated_tokens: int = 0,
    extra_meta: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """Convert an ``AgentResult`` into a trajectory record dict.

    Args:
        prompt_tokens: Number of tokens in the prompt (system + user + tools).
        generated_tokens: Number of tokens generated by the model.

    The output format::

        {
            "question": "...",
            "task_id": "...",
            "model_id": "...",
            "config": "...",
            "timestamp": "2026-05-28T12:00:00",
            "success": true,
            "error": null,
            "total_time": 5.2,
            "prompt_tokens": 200,
            "generated_tokens": 300,
            "total_tokens": 500,
            "final_answer": "...",
            "trajectory": {
                "type": "trajectory",
                "steps": [
                    {"action": "plan", "step_index": 0, "is_constrained": true, "args": {...}},
                    ...
                ]
            },
            ...extra_meta
        }
    """
    steps = []
    for s in agent_result.steps:
        step_record: Dict[str, Any] = {
            "action": s.tool_name or "(text_response)",
            "step_index": s.step_index,
            "is_constrained": s.is_constrained,
            "elapsed": round(s.elapsed, 3),
        }
        if s.tool_args:
            step_record["args"] = s.tool_args
        if s.tool_result:
            step_record["result"] = _truncate(s.tool_result, 500)
        steps.append(step_record)

    total = prompt_tokens + generated_tokens or agent_result.total_tokens

    record: Dict[str, Any] = {
        "question": agent_result.user_query,
        "task_id": task_id,
        "model_id": model_id,
        "config": config_name,
        "timestamp": datetime.now().isoformat(timespec="seconds"),
        "success": agent_result.success,
        "error": agent_result.error,
        "total_time": round(agent_result.total_time, 3),
        "prompt_tokens": prompt_tokens,
        "generated_tokens": generated_tokens,
        "total_tokens": total,
        "final_answer": _truncate(agent_result.final_answer, 1000) if agent_result.final_answer is not None else None,
        "trajectory_evaluate": True,
        "trajectory": {
            "type": "trajectory",
            "steps": steps,
        },
    }

    if extra_meta:
        record.update(extra_meta)

    return record


# ---------------------------------------------------------------------------
# Summary builder
# ---------------------------------------------------------------------------

def _build_summary(
    records: List[Dict[str, Any]],
    model_id: str = "",
    config_name: str = "",
) -> Dict[str, Any]:
    """Build a summary entry from a list of trajectory records."""
    n = len(records)
    total_prompt = sum(r.get("prompt_tokens", 0) for r in records)
    total_generated = sum(r.get("generated_tokens", 0) for r in records)
    total_all = sum(r.get("total_tokens", 0) for r in records)
    success_count = sum(1 for r in records if r.get("success"))

    return {
        "type": "_summary",
        "model_id": model_id,
        "config": config_name,
        "timestamp": datetime.now().isoformat(timespec="seconds"),
        "total_tasks": n,
        "total_prompt_tokens": total_prompt,
        "total_generated_tokens": total_generated,
        "total_tokens_all": total_all,
        "avg_prompt_tokens_per_task": round(total_prompt / max(n, 1), 1),
        "avg_generated_tokens_per_task": round(total_generated / max(n, 1), 1),
        "avg_tokens_per_task": round(total_all / max(n, 1), 1),
        "success_count": success_count,
        "success_rate": round(success_count / max(n, 1), 3),
    }


# ---------------------------------------------------------------------------
# Save (new file)
# ---------------------------------------------------------------------------

def save_trajectory(
    agent_result: AgentResult,
    filepath: str,
    model_id: str = "",
    config_name: str = "",
    task_id: str = "",
    prompt_tokens: int = 0,
    generated_tokens: int = 0,
    extra_meta: Optional[Dict[str, Any]] = None,
) -> str:
    """Write a single agent execution trace to a new JSON file (overwrites).

    The file contains a JSON array with one trajectory record followed
    by a ``_summary`` entry.
    """
    record = agent_result_to_record(
        agent_result, model_id=model_id, config_name=config_name,
        task_id=task_id, prompt_tokens=prompt_tokens,
        generated_tokens=generated_tokens, extra_meta=extra_meta,
    )
    summary = _build_summary([record], model_id=model_id, config_name=config_name)

    os.makedirs(os.path.dirname(filepath) or ".", exist_ok=True)
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump([record, summary], f, ensure_ascii=False, indent=2)

    return os.path.abspath(filepath)


# ---------------------------------------------------------------------------
# Append (existing or new file)
# ---------------------------------------------------------------------------

def append_trajectory(
    agent_result: AgentResult,
    filepath: str,
    model_id: str = "",
    config_name: str = "",
    task_id: str = "",
    prompt_tokens: int = 0,
    generated_tokens: int = 0,
    extra_meta: Optional[Dict[str, Any]] = None,
) -> str:
    """Append an agent execution trace to a JSON file.

    - Existing file with array → appends before the ``_summary`` entry (if any),
      then rebuilds the summary.
    - New file → creates array with record + summary.
    """
    record = agent_result_to_record(
        agent_result, model_id=model_id, config_name=config_name,
        task_id=task_id, prompt_tokens=prompt_tokens,
        generated_tokens=generated_tokens, extra_meta=extra_meta,
    )

    os.makedirs(os.path.dirname(filepath) or ".", exist_ok=True)

    existing: List[Dict[str, Any]] = []
    if os.path.isfile(filepath) and os.path.getsize(filepath) > 0:
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                data = json.load(f)
            if isinstance(data, list):
                existing = data
            else:
                existing = [data]
        except (json.JSONDecodeError, Exception):
            existing = []

    # Remove old summary entry if present
    trajectories = [r for r in existing if r.get("type") != "_summary"]
    trajectories.append(record)

    summary = _build_summary(trajectories, model_id=model_id, config_name=config_name)
    trajectories.append(summary)

    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(trajectories, f, ensure_ascii=False, indent=2)

    return os.path.abspath(filepath)


# ---------------------------------------------------------------------------
# Batch convenience
# ---------------------------------------------------------------------------

def save_trajectories_batch(
    results: List[AgentResult],
    filepath: str,
    model_id: str = "",
    config_name: str = "",
    task_ids: Optional[List[str]] = None,
    prompt_tokens_list: Optional[List[int]] = None,
    generated_tokens_list: Optional[List[int]] = None,
    extra_meta: Optional[Dict[str, Any]] = None,
) -> str:
    """Write multiple agent results to one JSON file.

    The file is a JSON array: trajectory records + a ``_summary`` entry
    at the end with aggregate token statistics.

    Args:
        results: List of AgentResult objects.
        filepath: Output path.
        model_id: Model identifier.
        config_name: Experiment config name.
        task_ids: Per-result task IDs (defaults to empty strings).
        prompt_tokens_list: Per-result prompt token counts.
        generated_tokens_list: Per-result generated token counts.
        extra_meta: Extra keys merged into every record.
    """
    if task_ids is None:
        task_ids = [""] * len(results)
    if prompt_tokens_list is None:
        prompt_tokens_list = [0] * len(results)
    if generated_tokens_list is None:
        generated_tokens_list = [0] * len(results)

    records = []
    for i, r in enumerate(results):
        tid = task_ids[i] if i < len(task_ids) else ""
        pt = prompt_tokens_list[i] if i < len(prompt_tokens_list) else 0
        gt = generated_tokens_list[i] if i < len(generated_tokens_list) else 0
        records.append(agent_result_to_record(
            r, model_id=model_id, config_name=config_name,
            task_id=tid, prompt_tokens=pt, generated_tokens=gt,
            extra_meta=extra_meta,
        ))

    summary = _build_summary(records, model_id=model_id, config_name=config_name)
    output = records + [summary]

    os.makedirs(os.path.dirname(filepath) or ".", exist_ok=True)
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)

    return os.path.abspath(filepath)


